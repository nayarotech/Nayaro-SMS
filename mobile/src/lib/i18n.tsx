export type Language = keyof typeof strings;
type Key = keyof (typeof strings)["en"];

const I18nContext = createContext<{ language: Language; setLanguage: (l: Language) => void; t: (key: Key) => string } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>("en");
  return <I18nContext.Provider value={{ language, setLanguage, t: (key) => strings[language][key] }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside <I18nProvider>");
  return context;
}

/** AD "YYYY-MM-DD" → "12 Asar 2075" (BS) in the chosen language. */
export function formatBs(ad: string, language: Language): string {
  const [y, m, d] = ad.slice(0, 10).split("-").map(Number);
  try {
    return new NepaliDate(new Date(y, m - 1, d)).format("D MMMM YYYY", language === "ne" ? "np" : "en");
  } catch {
    return ad;
  }
}
